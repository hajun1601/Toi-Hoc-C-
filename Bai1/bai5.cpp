// viết một chương trình khai báo biến a,b in ra kết quả.
#include <iostream>

using namespace std;

int main(){
    int a = 100, b = 200;
    cout << "A = 100, B = 200 \n tính + - * / " << endl;
    cout << " A + B = " << a + b << endl;
    cout << " A - B = " << a - b << endl;
    cout << " A * B = " << a * b << endl;
    cout << " A / B = " << a / b << endl;
}
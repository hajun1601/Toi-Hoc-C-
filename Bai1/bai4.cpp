// Làm chương trình thuật toán cơ bản + - * /
#include <iostream>

using namespace std;

int main(){
    cout << "2006 + 2026 = " << 2006 + 2026 << endl;
    cout << "2006 - 2026 = " << 2006 - 2026 << endl;
    cout << "2006 * 2026 = " << 2006 * 2026 << endl;
    cout << "2006 / 2026 = " << 2006 / 2026 << endl;
    return 0;
}